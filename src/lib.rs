//! # TypeCT (タイプ数カウンター)
//!
//! Windows 11 (64bitネイティブ) 向けに刷新された、Rust + egui 製の打鍵・マウスクリック数・マウス移動距離計測デスクトップアプリケーション。
//!
//! かつて Windows で愛用されていた Borland C++ 5.5 製フリーソフト「タイプ数カウンター (typect.exe)」の
//! シンプルさ・軽快さを継承しつつ、現代的なテクノロジースタックで再構築されています。
//!
//! ## 主な特徴
//! - **二重起動防止**: Windows Named Mutex (`single-instance`) による多重起動防止
//! - **日本語フォント確実表示**: Windows標準フォントを自動検出し、文字化け（豆腐化: □）を完全防止
//! - **低遅延グローバル入力監視**: `rdev` による独立スレッドでの監視と、キーロガーを行わない安全な集計
//! - **マウス移動距離計測**: カーソル移動量をリアルタイムにメートル/キロメートル単位で積算
//! - **キーボードヒートマップ**: QWERTY 配列上の打鍵頻度分布を視覚化
//! - **目標打鍵数トースト通知**: 1日の目標達成時に Windows ネイティブトースト通知でお祝い
//! - **カラーテーマ切替**: システム追従、ダーク、ライトテーマの自由な切り替え
//! - **Windows スタートアップ登録**: ワンクリックで Windows 起動時の常駐を登録/解除
//! - **CSV エクスポート**: 日別・時間帯別・キー別統計を CSV 出力
//! - **旧データ自動移行**: 同一フォルダ内の旧 `data`（打鍵）および `data2`（クリック）固定長バイナリからの自動引き継ぎ
//! - **タスクトレイ常駐**: 動的ツールチップ（本日の打鍵/クリック数表示）および最小化格納
//! - **省電力設計**: アイドル時・バックグラウンド時は待機時 CPU 0% を維持
//!
//! ## モジュール構成
//! - [`legacy`][] - 旧バージョン (typect) の固定長バイナリヘッダ解析
//! - [`model`][] - 打鍵・クリック・マウス移動距離集計データ構造体、日付ロールオーバー、永続化、CSV出力
//! - [`input`][] - 入力イベントメッセージ、プライバシー保護キーマッピング、距離換算
//! - [`font`][] - 日本語フォント探索・ロード
//! - [`tray`][] - 自己完結型タスクトレイアイコン生成
//! - [`heatmap`][] - キーボード配列レイアウト & ヒートマップ描画
//! - [`notify`][] - 目標達成トースト通知発行
//! - [`startup`][] - Windows スタートアップ登録管理
//! - [`app`][] - eframe / egui GUI アプリケーション本体

